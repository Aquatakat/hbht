"""Writes a family of combat parity's formula vectors (roadmap 2.9): 1.0's own combat functions run in the MIPS interpreter on a battle's
RAM with their inputs varied, for tests/HBHT.Rom.Tests/Formulas/<Family>Vectors.cs, which the port's same functions are checked against.

    python tools/aivectors/formulas.py melee                 # every melee vector, into tests/HBHT.Rom.Tests/Formulas/MeleeVectors.cs
    python tools/aivectors/formulas.py melee --only behind   # the vectors whose id has the text, printed, nothing written
    python tools/aivectors/formulas.py --list                # the families

A family is a module in families/ (families/melee.py is the first): FAMILY, its C# class's name, a docstring the table's comment is
made from, cases() listing its vectors and run(vector) running one. A vector is a dict:
    id       its name, unique in the family
    source   the state's RAM: cp05, or log:<session>/<battle>:<dump> (state.py)
    pokes    the changes to it, "name:args|..." (state.py)
    args     the function's arguments the family's test reads (slots and the like), a list of ints
    seed     the main stream's seed before the call
    script   draws to fix, {index: raw value} (draws.py; d100(r) is a d100 coming up r)
run returns (expect, callers): the results as an ordered list of (name, value), and the functions each draw came from. The test lays the
same state over the port's battle, makes the same pokes, sets its stream and script the same, calls the port's function and compares
"name=value ..." whole, the draws' count among them. Deterministic: running it again writes the same file.

Needs `pip install capstone numpy`, the 1.0 ROM and the checkpoints in roms/ (or HBHT_ROMS), and the parity logs in out/parity (or
HBHT_PARITY) for the vectors on their states. docs/reference-rig.md's "Replaying the original's AI" has the rest.
"""
import argparse
import importlib
import json
import os
import sys
import textwrap
import time
import traceback
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rig  # noqa: E402

TESTS = os.path.join(rig.REPO, 'tests', 'HBHT.Rom.Tests', 'Formulas')


def family(name):
    return importlib.import_module('families.' + name)


def work(task):
    name, vector = task
    t = time.time()
    try:
        expect, callers = family(name).run(vector)
        return vector['id'], expect, callers, time.time() - t, None
    except Exception:
        return vector['id'], None, None, time.time() - t, traceback.format_exc()


def line(expect):
    return ' '.join(f'{k}={v}' for k, v in expect)


def cs_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


TEMPLATE = '''namespace HBHT.Rom.Tests.Formulas;

@COMMENT@
internal static class @CLASS@Vectors
{
    public static readonly FormulaVector[] Vectors =
    [
@LINES@
    ];
}
'''


def write_cs(mod, name, vectors, results, path):
    lines = []
    for v in vectors:
        expect, callers = results[v['id']]
        script = ' '.join(f'{i}=0x{x:08X}' for i, x in sorted(v.get('script', {}).items()))
        args = ', '.join(str(a) for a in v.get('args', []))
        lines.append(f"        new({cs_string(v['id'])}, {cs_string(v['source'])}, {cs_string(v.get('pokes', ''))}, [{args}], "
                     f"0x{v['seed']:08X}u, {cs_string(script)},\n            {cs_string(line(expect))},\n"
                     f"            {cs_string(' '.join(callers))}),")
    doc = f'Generated by tools/aivectors (python tools/aivectors/formulas.py {name}), do not edit. ' + ' '.join((mod.__doc__ or '').split())
    comment = '\n'.join('// ' + l for l in textwrap.wrap(doc, 137))
    text = TEMPLATE.replace('@COMMENT@', comment).replace('@CLASS@', mod.FAMILY).replace('@LINES@', '\n'.join(lines))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return len(text.encode('utf-8'))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('family', nargs='?', help='the family module in families/')
    ap.add_argument('--list', action='store_true', help='list the families')
    ap.add_argument('--only', help='run only the vectors whose id has this text, print them, and write nothing')
    ap.add_argument('--jobs', type=int, default=min(os.cpu_count() or 1, 16))
    ap.add_argument('--roms', help='the folder with the 1.0 ROM and the checkpoints (default HBHT_ROMS, else roms/)')
    ap.add_argument('--out', help='the C# file (default tests/HBHT.Rom.Tests/Formulas/<Family>Vectors.cs)')
    a = ap.parse_args()
    if a.list or not a.family:
        for f in sorted(os.listdir(os.path.join(HERE, 'families'))):
            if f.endswith('.py') and not f.startswith('_'):
                print(f[:-3])
        return
    if a.roms:
        os.environ['HBHT_ROMS'] = a.roms

    mod = family(a.family)
    vectors = mod.cases()
    ids = [v['id'] for v in vectors]
    assert len(set(ids)) == len(ids), 'duplicate vector ids'
    if a.only:
        vectors = [v for v in vectors if a.only in v['id']]
    print(f'{a.family}: {len(vectors)} vectors; ROM {rig.rom_path()}', flush=True)

    rig.code()          # the disassembly once, before the workers need it
    import state
    for source in sorted({v['source'] for v in vectors}):
        state.ram(source)          # each state read once here, failing early if one is missing (the workers read their own)

    t0 = time.time()
    results = {}
    with Pool(max(1, min(a.jobs, len(vectors)))) as pool:
        for vid, expect, callers, seconds, error in pool.imap_unordered(work, [(a.family, v) for v in vectors], chunksize=1):
            if error:
                pool.terminate()
                sys.exit(f'{vid} failed after {seconds:.1f}s:\n{error}')
            results[vid] = (expect, callers)
            if a.only:
                print(f'{vid}: {line(expect)}\n    draws: {" ".join(callers)}', flush=True)
    print(f'ran in {time.time() - t0:.0f}s', flush=True)
    if a.only:
        return

    os.makedirs(rig.OUT, exist_ok=True)
    with open(os.path.join(rig.OUT, a.family + '.json'), 'w') as f:
        json.dump([dict(v, script={str(k): x for k, x in v.get('script', {}).items()}, expect=dict(results[v['id']][0]),
                        draws=results[v['id']][1]) for v in vectors], f, indent=1)
    path = a.out or os.path.join(TESTS, mod.FAMILY + 'Vectors.cs')
    size = write_cs(mod, a.family, vectors, results, path)
    print(f'{path}: {len(vectors)} vectors, {size} bytes')


if __name__ == '__main__':
    main()
